/**
 * Builds the "tamed" UX4G vendor stylesheet consumed at runtime.
 *
 * Reads the pinned, byte-exact UX4G CSS (never edited) and derives a runtime copy
 * that:
 *   1. has its 1,668 `!important` declarations removed, and
 *   2. is wrapped in `@layer ux4g`.
 *
 * WHY: measured in Phase 2 (scripts/ux4g-load-experiment.js) — loading UX4G as-is
 * under @layer still changes the current pages ~1.3-1.7% because its `!important`
 * rules beat the existing unlayered theme. Stripping them drops that to ~0.00%, so
 * UX4G loads invisibly and the migration can reveal it component-by-component by
 * removing existing overrides. See docs/UX4G-Decision-Note-R1-R2-R3.md (R-1, §9.3).
 *
 * The pinned original at public/admin_assets/libs/ux4g/css/ux4g-min.css is NOT
 * modified — this output is a generated build artifact.
 *
 * NOTE (future): stripping ALL !important also weakens UX4G's own utility classes
 * (.d-none etc.) for the eventual UX4G-styled end state. That only matters once
 * UX4G is the ACTIVE styling for a component; handle then via a dedicated
 * `ux4g-utilities` layer or selective retention. For invisible loading it is correct.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'public/admin_assets/libs/ux4g/css/ux4g-min.css');
const OUT = path.join(ROOT, 'public/css/ux4g-vendor.css');

const raw = fs.readFileSync(SRC, 'utf8');
const importantCount = (raw.match(/!important/g) || []).length;

// Strip `!important` (only ever appears as declaration priority in this minified
// stylesheet — no CSS value legitimately contains the literal token).
const tamed = raw.replace(/\s*!important/g, '');

const out =
    '/* GENERATED by scripts/build-ux4g-vendor.js — do not edit. */\n' +
    '/* Tamed UX4G v2.0.8: ' + importantCount + ' !important stripped, wrapped in @layer ux4g. */\n' +
    '@layer ux4g, tokens, components, pages;\n' +
    '@layer ux4g {\n' + tamed + '\n}\n';

fs.writeFileSync(OUT, out);
console.log(`build-ux4g-vendor: stripped ${importantCount} !important -> ${OUT} ` +
    `(${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
