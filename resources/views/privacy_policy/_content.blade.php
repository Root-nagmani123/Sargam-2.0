<section class="pp-section" id="pp-1">
    <h3>1. Introduction</h3>
    <p>SARGAM 2.0 is the integrated Training Management and Administrative Portal of the Lal Bahadur Shastri National Academy of Administration (LBSNAA), Mussoorie, Uttarakhand.</p>
    <p>The portal is designed to facilitate and streamline the Academy's academic, training, administrative and employee-related activities through a unified digital platform.</p>
    <p>LBSNAA is committed to protecting the privacy and confidentiality of personal information submitted, stored, processed or accessed through SARGAM 2.0. This Privacy Policy explains how personal information is collected, used, stored, protected and shared while accessing or using the portal.</p>
</section>

<section class="pp-section" id="pp-2">
    <h3>2. Information We Collect</h3>
    <p>Depending on the services and modules accessed, SARGAM 2.0 may collect and process the following categories of information:</p>
    <h4>A. Personal Information</h4>
    <ul>
        <li>Name, date of birth and gender, wherever required.</li>
        <li>Mobile number, email address and correspondence details.</li>
        <li>Photograph and other identification details, wherever applicable.</li>
        <li>Official identification or registration numbers.</li>
    </ul>
    <h4>B. Professional and Employment Information</h4>
    <ul>
        <li>Designation, department, section and office details.</li>
        <li>Employee identification and service-related information.</li>
        <li>Official contact and reporting details.</li>
    </ul>
    <h4>C. Academic and Training Information</h4>
    <ul>
        <li>Course and programme details.</li>
        <li>Officer Trainee registration and academic records.</li>
        <li>Attendance, examination and evaluation records.</li>
        <li>Feedback, assignments and training-related submissions.</li>
        <li>Course participation and performance-related information.</li>
    </ul>
    <h4>D. Administrative Information</h4>
    <ul>
        <li>Leave, tour and other administrative applications.</li>
        <li>Hostel and accommodation-related records, wherever applicable.</li>
        <li>Official requests, approvals and workflow transactions.</li>
        <li>Documents and attachments submitted through the portal.</li>
    </ul>
    <h4>E. Technical Information</h4>
    <p>For security, monitoring and operational purposes, the portal may automatically collect:</p>
    <ul>
        <li>IP address.</li>
        <li>Browser type and operating system.</li>
        <li>Login date and time.</li>
        <li>Access logs and session information.</li>
        <li>Pages and modules accessed.</li>
        <li>Security and error logs.</li>
    </ul>
</section>

<section class="pp-section" id="pp-3">
    <h3>3. Purpose of Collection and Processing</h3>
    <p>Information collected through SARGAM 2.0 is used strictly for official, administrative, academic, training and operational purposes, including:</p>
    <ul>
        <li>Managing Officer Trainee and employee records.</li>
        <li>Facilitating academic and training activities.</li>
        <li>Managing courses, schedules, attendance and assessments.</li>
        <li>Processing administrative applications and approvals.</li>
        <li>Providing employee-centric and trainee-centric services.</li>
        <li>Facilitating communication between authorised users and Academy officials.</li>
        <li>Generating reports, dashboards and administrative analytics.</li>
        <li>Maintaining system security, monitoring and preventing unauthorised access.</li>
        <li>Integrating authorised applications and services for seamless functioning.</li>
    </ul>
    <p>Personal information shall not be used for purposes unrelated to the legitimate functions of the Academy, except where permitted or required under applicable law.</p>
</section>

<section class="pp-section" id="pp-4">
    <h3>4. Data Sharing and Disclosure</h3>
    <p>LBSNAA does not sell, rent or commercially trade personal information collected through SARGAM 2.0.</p>
    <p>Information may be shared with:</p>
    <ul>
        <li>Authorised officers, departments and sections of LBSNAA for official purposes.</li>
        <li>Government Ministries, Departments and organisations, wherever required for official functions.</li>
        <li>Authorised government platforms and applications integrated with SARGAM 2.0.</li>
        <li>Technology and service providers engaged for hosting, maintenance, security and technical support, subject to appropriate safeguards and applicable requirements.</li>
        <li>Competent authorities, where disclosure is required under applicable laws, rules or government directions.</li>
    </ul>
    <p>Access to personal information shall be restricted to authorised persons on a need-to-know basis.</p>
</section>

<section class="pp-section" id="pp-5">
    <h3>5. Integration with Other Government Applications</h3>
    <p>SARGAM 2.0 may provide integration facilities with other authorised government applications and digital platforms to enable seamless access to services and information exchange.</p>
    <p>Such integration may involve the exchange of limited user information, such as user identification, name, official registration details or other information necessary for the intended service.</p>
    <p>Appropriate technical and security measures shall be adopted to ensure that information exchanged between integrated applications is protected against unauthorised access, misuse or disclosure.</p>
</section>

<section class="pp-section" id="pp-6">
    <h3>6. Data Security</h3>
    <p>LBSNAA takes appropriate technical and organisational measures to safeguard information maintained in SARGAM 2.0.</p>
    <p>These measures may include:</p>
    <ul>
        <li>Authentication and access-control mechanisms.</li>
        <li>Role-based access permissions.</li>
        <li>Secure communication using HTTPS/SSL.</li>
        <li>Protection against unauthorised access and data breaches.</li>
        <li>Monitoring of login activities and system logs.</li>
        <li>Regular security updates and maintenance.</li>
        <li>Data backup and recovery mechanisms.</li>
        <li>Appropriate safeguards for data sharing and application integration.</li>
    </ul>
    <p>However, users are also responsible for maintaining the confidentiality of their login credentials and must not share their passwords or authentication details with unauthorised persons.</p>
</section>

<section class="pp-section" id="pp-7">
    <h3>7. Cookies and Session Management</h3>
    <p>SARGAM 2.0 may use cookies and session-management technologies to facilitate secure login, maintain authenticated sessions and improve the functionality of the portal.</p>
    <p>These technologies are used for operational and security purposes. Users should ensure that their browsers support cookies and JavaScript for the proper functioning of the portal.</p>
</section>

<section class="pp-section" id="pp-8">
    <h3>8. Data Retention</h3>
    <p>Personal information shall be retained only for the period necessary to fulfil the purposes for which it was collected or as required under applicable Government of India rules, regulations, departmental instructions and record-retention policies.</p>
    <p>Official records, academic records, administrative transactions and other institutional documents may be retained for the prescribed periods in accordance with applicable government record-management requirements.</p>
    <p>Information that is no longer required shall be securely deleted, anonymised or otherwise disposed of, subject to applicable legal and administrative obligations.</p>
</section>

<section class="pp-section" id="pp-9">
    <h3>9. User Responsibilities</h3>
    <p>All users accessing SARGAM 2.0 are expected to:</p>
    <ul>
        <li>Maintain the confidentiality of their login credentials.</li>
        <li>Access only those records and services for which they are authorised.</li>
        <li>Provide accurate and updated information wherever required.</li>
        <li>Avoid sharing confidential information with unauthorised persons.</li>
        <li>Log out after completing their work, particularly when using shared computers.</li>
        <li>Immediately report suspected unauthorised access or security incidents to the concerned authority.</li>
    </ul>
    <p>Any misuse of the portal or unauthorised access may be dealt with in accordance with applicable Government rules and regulations.</p>
</section>

